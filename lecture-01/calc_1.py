"""Розрахунки для анімацій Лекції 1 (випуски 1.1–1.3).

Кожне число, яке з'являється в кадрі або задає геометрію руху, береться звідси.
Запуск `python calc_1.py` друкує зведену таблицю для фактчеку.
"""
from math import sqrt, pi, cos, radians, atanh

G = 9.8                 # м/с², як у сценарії (Додаток Б)
G_MOON = 1.62           # м/с²

# ── №1 Баланс сил: падіння людини плазом ────────────────────────────────────
V_TERM = 55.0           # м/с, усталена швидкість плазом (сценарій 2.2)
V_TERM_CANDLE = 90.0    # м/с, «свічкою»
T_95 = V_TERM / G * atanh(0.95)   # с, коли швидкість досягає 95 % усталеної


def v_skydiver(t):
    """v(t) при опорі ~ v²: v = v_t · th(g t / v_t)."""
    from math import tanh
    return V_TERM * tanh(G * t / V_TERM)


# ── №2 Куб проти квадрата ────────────────────────────────────────────────────
R_SCALE = 2             # радіус ×2
VOLUME_FACTOR = R_SCALE ** 3      # вага ~ r³ → ×8
AREA_FACTOR = R_SCALE ** 2        # опір ~ r² → ×4
WEIGHT_PER_AREA = VOLUME_FACTOR // AREA_FACTOR   # ×2

# ── №5 П'ять спостерігачів ──────────────────────────────────────────────────
V_CONDUCTOR = 1.0       # м/с, провідник іде коридором назустріч
V_TRAIN = 20.0          # м/с = 72 км/год
KYIV_LAT = 50.45        # °
EARTH_R = 6.371e6       # м
SIDEREAL_DAY = 86164.1  # с
V_ROT_EQUATOR = 2 * pi * EARTH_R / SIDEREAL_DAY          # ≈465 м/с
V_ROT_KYIV = V_ROT_EQUATOR * cos(radians(KYIV_LAT))      # ≈296 м/с
V_ORBIT_EARTH = 29.78e3                                  # м/с

# ── №10 / №19 Ньютонова гармата і Місяць ────────────────────────────────────
V_FIRST_COSMIC = sqrt(G * EARTH_R)                      # ≈7,9 км/с
MOON_R = 3.844e8        # м
MOON_T = 27.3 * 86400   # с (задача 16)
A_MOON = 4 * pi ** 2 * MOON_R / MOON_T ** 2             # ≈2,7·10⁻³ м/с²
G_OVER_A_MOON = G / A_MOON                              # ≈3600
DIST_RATIO_SQ = (MOON_R / EARTH_R) ** 2                 # ≈3640
MOON_FALL_PER_MINUTE = 0.5 * A_MOON * 60 ** 2           # ≈4,9 м — як яблуко за 1 с
APPLE_FALL_1S = 0.5 * G * 1 ** 2                        # 4,9 м

# ── №11 Площа = шлях ─────────────────────────────────────────────────────────
V_CONST = 10.0          # м/с
T_CONST = 4.0           # с
S_CONST = V_CONST * T_CONST   # 40 м

# ── №13 / Е3 Незалежність осей ──────────────────────────────────────────────
H_DROP = 1.0            # м
VX_LAUNCH = 4.5         # м/с
T_DROP = sqrt(2 * H_DROP / G)        # ≈0,452 с
X_LAUNCH = VX_LAUNCH * T_DROP        # ≈2,03 м
SLOWMO_13 = 8                        # у кадрі час сповільнено ×8

# ── №14 Повітряна куля над Києвом ───────────────────────────────────────────
KYIV_LON = 30.52        # °
LISBON_LON = -9.14      # °
HOURS_KYIV_LISBON = (KYIV_LON - LISBON_LON) / (360 / (SIDEREAL_DAY / 3600))  # ≈2,6 год

# ── №15 М'яч у вагоні ────────────────────────────────────────────────────────
V0_BALL = 5.0           # м/с угору
T_FLIGHT = 2 * V0_BALL / G           # ≈1,02 с
H_BALL = V0_BALL ** 2 / (2 * G)      # ≈1,28 м
L_BALL = V_TRAIN * T_FLIGHT          # ≈20,4 м
SLOWMO_15 = 4

# ── №18 Масштаб Коріоліса ────────────────────────────────────────────────────
CYCLONE_D = 1.0e6       # м (1000 км)
SINK_D = 0.40           # м
SCALE_RATIO_18 = CYCLONE_D / SINK_D  # 2,5·10⁶
OMEGA_EARTH = 7.3e-5    # рад/с (задача 17)
V_SINK = 0.1            # м/с
A_CORIOLIS_SINK = 2 * OMEGA_EARTH * V_SINK * 0.766   # ≈1,1·10⁻⁵ м/с²
G_OVER_CORIOLIS = G / A_CORIOLIS_SINK                # ≈880 000


def ua(x, nd=2):
    """Число з українською десятковою комою — для Text / T()."""
    return f"{x:.{nd}f}".replace(".", ",")


def ua_tex(x, nd=2):
    """Те саме для MathTex / M(): у TeX кома без {,} дає зайвий пробіл («20, 4»)."""
    return f"{x:.{nd}f}".replace(".", "{,}")


if __name__ == "__main__":
    rows = [
        ("№1 час до 95 % усталеної швидкості", T_95, "с"),
        ("№5 обертання Землі на широті Києва", V_ROT_KYIV, "м/с"),
        ("№10 перша космічна швидкість", V_FIRST_COSMIC / 1000, "км/с"),
        ("№19 доцентрове прискорення Місяця", A_MOON, "м/с²"),
        ("№19 g / a_Місяця", G_OVER_A_MOON, ""),
        ("№19 (R_Місяця / R_Землі)²", DIST_RATIO_SQ, ""),
        ("№19 Місяць «падає» за хвилину", MOON_FALL_PER_MINUTE, "м"),
        ("№11 шлях за 4 с при 10 м/с", S_CONST, "м"),
        ("№13 час падіння з 1 м", T_DROP, "с"),
        ("№13 політ убік при 4,5 м/с", X_LAUNCH, "м"),
        ("№14 Київ → Лісабон обертанням Землі", HOURS_KYIV_LISBON, "год"),
        ("№15 час польоту м'яча", T_FLIGHT, "с"),
        ("№15 висота м'яча", H_BALL, "м"),
        ("№15 вагон проїхав", L_BALL, "м"),
        ("№18 відношення масштабів", SCALE_RATIO_18, ""),
        ("№18 g / a_Коріоліса", G_OVER_CORIOLIS, ""),
    ]
    for name, val, unit in rows:
        print(f"{name:42s} {val:14.6g} {unit}")
